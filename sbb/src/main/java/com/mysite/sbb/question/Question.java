package com.mysite.sbb.question;

import java.time.LocalDateTime;
import java.util.List;

import com.mysite.sbb.answer.Answer;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.OneToMany;
import lombok.Getter;
import lombok.Setter;
/*
 * [Question 엔티티 = question 테이블과 1:1로 대응하는 클래스]
 *
 * ── 서버 시작 시 생성되는 테이블 (실제 DDL 로그 확인값) ───────────────
 *   create table question (
 *       id          integer generated by default as identity,   ← 기본키
 *       author_id   bigint,                                      ← 작성자(site_user.id) FK
 *       create_date timestamp(6),
 *       modify_date timestamp(6),
 *       subject     varchar(200),                                ← @Column(length = 200)
 *       content     TEXT,                                        ← @Column(columnDefinition = "TEXT")
 *       primary key (id)
 *   )
 *   create table question_voter (                                ← @ManyToMany voter 연결 테이블
 *       question_id integer not null,
 *       voter_id    bigint  not null,
 *       primary key (question_id, voter_id)
 *   )
 *   ※ answer 테이블의 question_id 가 question.id 를 가리키는 FK 를 가집니다. (Answer 엔티티 참고)
 *
 * ── 애너테이션 역할 ───────────────────────────────────────────────
 *   @Getter / @Setter : Lombok 이 getXxx(), setXxx() 를 자동 생성합니다. (예: getSubject(), setSubject())
 *   @Entity           : JPA 가 관리하는 DB 테이블 클래스임을 표시합니다.
 *
 * ── 연관관계 기본값이 만드는 SQL 요약 ─────────────────────────────────
 *   author        (@ManyToOne, 기본 EAGER)   : 질문 조회 시 site_user 를 LEFT JOIN 으로 함께 가져옴
 *   answerList    (@OneToMany, 기본 LAZY)    : 실제로 쓸 때 "select ... from answer al1_0 ... where al1_0.question_id=?"
 *   voter         (@ManyToMany, 기본 LAZY)   : 실제로 쓸 때 "select ... from question_voter v1_0 join site_user ..."
 */
@Getter
@Setter
@Entity
public class Question { // 질문 하나의 정보를 저장할 용도의  질문 엔티티 클래스 (question 테이블 과 연결)
	
	// [@Id] 기본키(PK)입니다.
	// [@GeneratedValue(strategy = IDENTITY)] DB 가 자동 증가로 번호를 매깁니다.
	//   INSERT 문의 id 자리에 default 가 들어가는 이유입니다.
	@Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Integer id; //질문  데이터의 고유 번호

	// [@Column(length = 200)] 열 타입 varchar(200) 으로 만듭니다. 최대 200 글자까지 저장됩니다.
	//   ※ 입력 검사 쪽 @Size(max = 200) (QuestionForm) 과 같은 기준입니다.
    @Column(length = 200)
    private String subject; //질문 제목

    // [@Column(columnDefinition = "TEXT")] 길이 제한이 거의 없는 TEXT 타입으로 만듭니다.
    @Column(columnDefinition = "TEXT")
    private String content; //질문 내용

	// 자바 LocalDateTime → DB timestamp(6) 열 (create_date)
	// 목록 조회의 "order by create_date desc" 정렬 기준이 되는 열입니다.
    private LocalDateTime createDate; //질문 작성 일시
    
	// [연관관계 1] 질문(Question) 1 : 답변(Answer) N  →  @OneToMany
	//   · mappedBy = "question"
	//       → 외래키(answer.question_id)는 Answer 쪽 question 필드가 관리합니다.
	//         질문 쪽은 "거울" 역할이라 테이블에 열이 추가되지 않습니다.
	//   · cascade = CascadeType.REMOVE
	//       → 질문을 delete 하면 연결된 답변을 먼저 조회해서 같이 삭제합니다.
	//         실제 로그 순서: select 질문 → select 답변 목록 → delete question_voter → delete answer_voter
	//                        → delete answer → delete question
    @OneToMany(mappedBy = "question", cascade = CascadeType.REMOVE)
    private List<Answer> answerList; //이 질문에 달린 답변 목록 
    
}

















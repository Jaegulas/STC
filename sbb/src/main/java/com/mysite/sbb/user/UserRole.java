package com.mysite.sbb.user;
// ↑ 이 파일은 com.mysite.sbb.user 폴더에 속한다는 뜻입니다.


import lombok.Getter;
// ↑ Getter 기능을 가져옵니다. 변수 값을 꺼내는 메서드를 자동으로 만들어 줍니다.


// ============================================================
// [열거형 타입(enum)이란?]
// 정해진 값(상수)만 모아 둔 타입입니다.
// 이 타입의 변수에는 목록에 있는 값만 넣을 수 있습니다.
// 여기서는 UserRole 타입의 값이 ADMIN, USER 둘뿐입니다.
// ============================================================
@Getter
public enum UserRole {
// ↑ public  : 다른 파일에서도 이 타입을 사용할 수 있습니다.
//   enum    : "이것은 열거형 타입이다"라고 알려 주는 키워드입니다.
//   UserRole: 타입의 이름입니다. 파일 이름(UserRole.java)과 같아야 합니다.


    // ------------------------------------------------------------
    // [상수 목록] 이 타입이 가질 수 있는 값들입니다.
    // 상수란 프로그램이 실행되는 동안 바뀌지 않는 값입니다.
    // ------------------------------------------------------------

    ADMIN("ROLE_ADMIN"),
    // ↑ ADMIN : 상수(고정된 값) 하나의 이름입니다.
    //           사용할 때는 UserRole.ADMIN 이라고 씁니다.
    //   ("ROLE_ADMIN") : ADMIN 에 붙인 설명 글자입니다.
    //                    이 글자는 아래 생성자를 통해 저장됩니다.
    //   , : 다음 상수가 있다는 뜻입니다.


    USER("ROLE_USER");
    // ↑ USER : 두 번째 상수 이름입니다. UserRole.USER 라고 씁니다.
    //   ("ROLE_USER") : USER 에 붙인 설명 글자입니다.
    //   ; : 상수 목록이 여기서 끝난다는 뜻입니다.


    // ------------------------------------------------------------
    // [생성자] 상수를 만들 때 실행되는 설정 코드입니다.
    // ADMIN("ROLE_ADMIN") 을 만나면 이 생성자가 실행됩니다.
    // ------------------------------------------------------------
    UserRole(String value) {
    // ↑ String value : 괄호 안의 글자("ROLE_ADMIN")를 받아 value 라는 이름으로 부릅니다.

        this.value = value;
        // ↑ 받은 글자를 변수 value 에 저장합니다.
        //   this.value : 지금 만들어지는 상수(예: ADMIN)가 가진 value 변수입니다.
        //   = value    : 받은 글자를 그 변수에 넣습니다.
    }

    // ------------------------------------------------------------
    // [변수] 각 상수가 글자를 저장해 두는 칸입니다.
    // ------------------------------------------------------------
    private String value;
    //   private: 이 파일 밖에서 직접 바꾸지 못하게 막습니다.
    //            대신 @Getter 가 만든 getValue() 로 값을 꺼낼 수 있습니다.
}
package com.mysite.sbb.answer;

import java.time.LocalDateTime;

import com.mysite.sbb.question.Question;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.ManyToOne;
import lombok.Getter;
import lombok.Setter;
/*
 * [Answer 엔티티 = answer 테이블과 1:1로 대응하는 클래스]
 *
 * ── 클래스 한눈에 보기 ─────────────────────────────────────────────
 *   Answer 클래스  ↔  answer 테이블        (클래스 이름 → 소문자 테이블 이름)
 *   필드(변수)      ↔  열(컬럼)            (camelCase → snake_case: createDate → create_date)
 *   객체 1개        ↔  행(레코드) 1줄
 *
 * ── 서버가 시작될 때 만들어지는 테이블 (application.properties 의 ddl-auto=update 때문에 자동 생성)
 *   create table answer (
 *       id          integer generated by default as identity,   ← @Id + IDENTITY : DB가 1,2,3... 자동 증가
 *       question_id integer,                                     ← @ManyToOne question 의 외래키(FK)
 *       author_id   bigint,                                      ← @ManyToOne author 의 외래키(FK)
 *       create_date timestamp(6),
 *       modify_date timestamp(6),
 *       content     TEXT,                                        ← columnDefinition = "TEXT"
 *       primary key (id)
 *   )
 *   create table answer_voter (                                  ← @ManyToMany voter 의 연결(중간) 테이블
 *       answer_id integer not null,
 *       voter_id  bigint  not null,
 *       primary key (answer_id, voter_id)                        ← 같은 사람이 두 번 추천하면 PK 충돌 → 한 번만 저장
 *   )
 *   alter table answer add constraint ... foreign key (question_id) references question   ← FK 제약 조건
 *
 * ── 애너테이션 역할 ───────────────────────────────────────────────
 *   @Getter / @Setter : Lombok 이 getXxx(), setXxx() 를 자동 생성합니다. (SQL과는 무관)
 *   @Entity           : "JPA가 관리하는 DB 테이블 클래스"라는 표시입니다. 이 표시가 있어야 Repository 가 이 클래스를 다룹니다.
 *
 * ── 연관관계 기본값이 SQL을 어떻게 바꾸는지 (실제 실행 로그로 확인함) ─────────────
 *   @ManyToOne 의 기본 fetch = EAGER(즉시 로딩) :
 *       답변을 조회하면 question, question.author 를 "LEFT JOIN" 으로 한 번에 같이 가져옵니다.
 *   @ManyToMany 의 기본 fetch = LAZY(지연 로딩) :
 *       voter 목록은 실제로 쓰는 순간(예: voter.add(), #lists.size(answer.voter))에 별도 select 가 나갑니다.
 */
@Getter
@Setter
@Entity
public class Answer { //답변 엔티티 클래스 (answer 테이블과 1:1 연결됨)
	
	// ─────────────────────────────────────────────────────────────────────
	// 변수 1. id (기본키, 답변 번호)
	// ─────────────────────────────────────────────────────────────────────

	// [@Id]
	//   - 이 변수가 기본키(Primary Key)라는 표시입니다. 행 하나를 구분하는 번호입니다.
	//   - 중복될 수 없고, 비어 있으면 안 됩니다.
	//
	// [@GeneratedValue(strategy = GenerationType.IDENTITY)]
	//   - 번호를 DB 가 1, 2, 3 ... 순서로 자동으로 채웁니다.
	//   - 그래서 답변을 저장하는 INSERT 문의 id 자리에는 default 가 들어갑니다.
	//       insert into answer (author_id, content, create_date, modify_date, question_id, id)
	//       values (?, ?, ?, ?, ?, default)
	//   - 저장이 끝나면 DB 가 정한 번호가 이 id 에 채워진 상태로 돌아옵니다.
	//     답변 등록 후 "질문 상세 + #answer_번호" 주소를 만들 때 이 값을 사용합니다. (AnswerController.createAnswer)
	//
	// [Integer 를 쓴 이유]
	//   - Integer 는 값이 없는 상태(null)를 가질 수 있습니다. 새로 만든 답변 객체는 저장 전까지 id 가 null 입니다.
	//   - Repository.save() 는 id 가 null 이면 INSERT, 값이 있으면 UPDATE 를 실행합니다.
	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	private Integer id;  // 답변 번호 (DB 가 자동으로 채움)

	// ─────────────────────────────────────────────────────────────────────
	// 변수 2. content (답변 내용)
	// ─────────────────────────────────────────────────────────────────────

	// [@Column(columnDefinition = "TEXT")]
	//   - 열의 DB 타입을 TEXT 로 직접 지정합니다. 답변은 길 수 있으므로 길이 제한이 거의 없는 타입을 씁니다.
	//   - 저장되는 값은 마크다운 문법으로 쓴 글입니다. 화면에서는 CommonUtil.markdown() 이 HTML 로 바꿔서 보여 줍니다.
	//   - 입력 검사는 AnswerForm 의 @NotEmpty 가 담당합니다. (비어 있으면 저장하지 않음)
	@Column(columnDefinition = "TEXT")
	private String content;  // 답변 내용

	// ─────────────────────────────────────────────────────────────────────
	// 변수 3. createDate (작성 일시)
	// ─────────────────────────────────────────────────────────────────────

	// LocalDateTime 은 날짜와 시각을 함께 담는 자바 자료형입니다. DB 에서는 timestamp(6) 열이 됩니다.
	//   - 값은 AnswerService.create() 에서 LocalDateTime.now() 로 넣습니다. (지금 시각)
	//   - 화면은 이 값을 yyyy-MM-dd HH:mm 형식으로 바꿔서 보여 줍니다. (#temporals.format)
	private LocalDateTime createDate;  // 답변 작성 일시

	// ─────────────────────────────────────────────────────────────────────
	// 변수 4. question (이 답변이 달린 질문)  ─ N : 1 관계
	// ─────────────────────────────────────────────────────────────────────

	// [@ManyToOne(fetch = FetchType.EAGER)]
	//   - 답변 여러 개가 질문 1개에 속하는 관계입니다. (N : 1)
	//   - answer 테이블에 question_id 열(외래키)이 생기고, 질문의 id 를 저장합니다.
	//   - 이 변수가 있어야 답변에서 질문을 찾을 수 있습니다.
	//       예) AnswerController 의 추천/삭제/수정 메서드는 answer.getQuestion().getId() 로
	//           "질문 상세 페이지 주소"를 만들어 redirect 합니다.
	//
	//   fetch = FetchType.EAGER (즉시 로딩)
	//   - 답변을 조회할 때 질문 정보를 같은 SELECT 안에서 LEFT JOIN 으로 함께 가져옵니다.
	//   - 답변 1개를 찾을 때 실행되는 실제 SQL (실행 로그 확인값):
	//       select a1_0.id, a2_0.id, a2_0.email, a2_0.password, a2_0.username, a1_0.content, a1_0.create_date, a1_0.modify_date,
	//              q1_0.id, a3_0.id, a3_0.email, a3_0.password, a3_0.username, q1_0.content, q1_0.create_date, q1_0.modify_date,
	//              q1_0.subject
	//       from answer a1_0
	//       left join site_user a2_0 on a2_0.id=a1_0.author_id
	//       left join question q1_0  on q1_0.id=a1_0.question_id
	//       left join site_user a3_0 on a3_0.id=q1_0.author_id
	//       where a1_0.id=?
	//     → 답변, 답변 작성자, 질문, 질문 작성자까지 한 번의 SELECT 로 가져옵니다.
	//       질문의 작성자(a3_0)까지 함께 JOIN 되는 이유는 question 변수의 author 도 EAGER 이기 때문입니다.
	//
	//   - 참고: 여기서 fetch 를 LAZY 로 바꾸면(FetchType.LAZY) 질문은 실제로 사용할 때 따로 SELECT 합니다.
	//     이 프로젝트는 EAGER 를 사용합니다. 주석 처리된 LAZY 예시는 적지 않았습니다.
    @ManyToOne //(fetch = FetchType.EAGER) // 즉시 로딩 (답변을 읽을 때 질문도 함께 읽음)
    private Question question; //이 답변이 달린 부모 질문 객체  
}










